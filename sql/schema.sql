-- Skema database SMB Dharmakirti (PostgreSQL / Supabase).
-- Aman dijalankan berulang kali. Aplikasi menjalankan berkas ini sendiri saat pertama kali tersambung.
-- Semua tanggal disimpan sebagai teks YYYY-MM-DD (WIB), jam sebagai HH:MM.

CREATE TABLE IF NOT EXISTS pengguna (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nip TEXT,
  nama TEXT NOT NULL,
  nama_dharma TEXT,
  hp TEXT NOT NULL UNIQUE,
  is_pengajar INTEGER NOT NULL DEFAULT 1,
  level TEXT CHECK (level IN ('guru', 'asisten')),
  tipe TEXT CHECK (tipe IN ('tetap', 'cadangan')),
  is_admin INTEGER NOT NULL DEFAULT 0,
  is_petugas INTEGER NOT NULL DEFAULT 0,
  aktif INTEGER NOT NULL DEFAULT 1,
  pin_hash TEXT,
  undangan_kode TEXT UNIQUE,
  undangan_kedaluwarsa TEXT,
  gagal_login INTEGER NOT NULL DEFAULT 0,
  kunci_sampai TEXT,
  dibuat TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD'),
  jabatan TEXT CHECK (jabatan IN ('kepala', 'wakil', 'bendahara', 'sekretaris'))
);
CREATE UNIQUE INDEX IF NOT EXISTS pengguna_nip ON pengguna (nip) WHERE nip IS NOT NULL;

CREATE TABLE IF NOT EXISTS kelas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL UNIQUE,
  urutan INTEGER NOT NULL DEFAULT 0
);

-- Satu slot = satu blok waktu mingguan (mis. Pagi, Siang) dengan mode absennya sendiri.
CREATE TABLE IF NOT EXISTS slot (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  hari INTEGER NOT NULL DEFAULT 0,
  jam_mulai TEXT NOT NULL,
  jam_selesai TEXT NOT NULL,
  mode TEXT NOT NULL CHECK (mode IN ('konfirmasi', 'masuk')),
  scan_mulai TEXT NOT NULL,
  scan_selesai TEXT NOT NULL,
  toleransi_menit INTEGER NOT NULL DEFAULT 10
);

-- Jadwal tetap. UNIQUE(pengguna_id, slot_id) mencegah satu orang mengajar dua kelas di slot yang sama.
-- Satu kelas boleh punya sampai 2 pembina (dijaga di aplikasi, yang kedua hanya ditetapkan admin).
CREATE TABLE IF NOT EXISTS penugasan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
  kelas_id INTEGER NOT NULL REFERENCES kelas(id) ON DELETE CASCADE,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  peran TEXT NOT NULL CHECK (peran IN ('guru', 'asisten')),
  mulai TEXT NOT NULL DEFAULT '0000-01-01',
  UNIQUE (pengguna_id, slot_id)
);

CREATE TABLE IF NOT EXISTS izin (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
  tanggal TEXT NOT NULL,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  jenis TEXT NOT NULL CHECK (jenis IN ('sakit', 'izin', 'tugas')),
  alasan TEXT,
  status TEXT NOT NULL DEFAULT 'menunggu' CHECK (status IN ('menunggu', 'disetujui', 'ditolak')),
  diputus_oleh INTEGER REFERENCES pengguna(id) ON DELETE SET NULL,
  dibuat TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (pengguna_id, tanggal, slot_id)
);

-- Penugasan khusus satu hari yang dibuat admin: pengganti, asisten dipindah kelas, atau pembina tambahan (kedua).
CREATE TABLE IF NOT EXISTS tugas_harian (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal TEXT NOT NULL,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  kelas_id INTEGER NOT NULL REFERENCES kelas(id) ON DELETE CASCADE,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
  peran TEXT NOT NULL CHECK (peran IN ('guru', 'asisten')),
  jenis TEXT NOT NULL CHECK (jenis IN ('pengganti', 'pindah', 'tambahan')),
  menggantikan_id INTEGER REFERENCES pengguna(id) ON DELETE SET NULL,
  dari_kelas_id INTEGER REFERENCES kelas(id) ON DELETE SET NULL,
  dibuat_oleh INTEGER REFERENCES pengguna(id) ON DELETE SET NULL,
  dibuat TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (tanggal, slot_id, pengguna_id)
);

-- Hanya terisi lewat scan QR. Tidak ada endpoint untuk input manual.
CREATE TABLE IF NOT EXISTS absensi (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal TEXT NOT NULL,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
  kelas_id INTEGER NOT NULL REFERENCES kelas(id) ON DELETE CASCADE,
  peran TEXT NOT NULL,
  jenis_tugas TEXT NOT NULL,
  jam_scan TEXT NOT NULL,
  waktu_scan TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('hadir', 'terlambat')),
  petugas_id INTEGER REFERENCES pengguna(id) ON DELETE SET NULL,
  UNIQUE (tanggal, slot_id, pengguna_id)
);

-- Hari libur: harian (satu tanggal, wajib beralasan) atau libur semester (rentang tanggal).
CREATE TABLE IF NOT EXISTS libur (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jenis TEXT NOT NULL CHECK (jenis IN ('harian', 'semester')),
  mulai TEXT NOT NULL,
  selesai TEXT NOT NULL,
  alasan TEXT NOT NULL,
  dibuat_oleh INTEGER REFERENCES pengguna(id) ON DELETE SET NULL
);

-- Data siswa. NIK hanya angka (16 digit).
CREATE TABLE IF NOT EXISTS murid (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nik TEXT NOT NULL UNIQUE,
  nama TEXT NOT NULL,
  kelas_id INTEGER NOT NULL REFERENCES kelas(id),
  tempat_lahir TEXT NOT NULL,
  tanggal_lahir TEXT NOT NULL,
  hp TEXT,
  nama_ortu TEXT NOT NULL,
  hp_ortu TEXT NOT NULL,
  asal_sekolah TEXT NOT NULL,
  aktif INTEGER NOT NULL DEFAULT 1,
  dibuat TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD')
);

-- Absensi siswa diisi pembina kelas setelah ia sendiri absen lewat scan QR.
CREATE TABLE IF NOT EXISTS absensi_murid (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal TEXT NOT NULL,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  kelas_id INTEGER NOT NULL REFERENCES kelas(id) ON DELETE CASCADE,
  murid_id INTEGER NOT NULL REFERENCES murid(id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('hadir', 'izin', 'sakit', 'alpa')),
  dicatat_oleh INTEGER REFERENCES pengguna(id) ON DELETE SET NULL,
  waktu TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (tanggal, slot_id, murid_id)
);

-- Materi yang diajarkan, satu catatan per kelas per sesi.
CREATE TABLE IF NOT EXISTS materi (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal TEXT NOT NULL,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  kelas_id INTEGER NOT NULL REFERENCES kelas(id) ON DELETE CASCADE,
  isi TEXT NOT NULL,
  dicatat_oleh INTEGER REFERENCES pengguna(id) ON DELETE SET NULL,
  waktu TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (tanggal, slot_id, kelas_id)
);

CREATE TABLE IF NOT EXISTS sesi_login (
  token_hash TEXT PRIMARY KEY,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
  kedaluwarsa TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS pengaturan (
  kunci TEXT PRIMARY KEY,
  nilai TEXT
);

-- Surat permohonan pencairan honor: satu nomor surat per bulan, dipakai ulang saat dicetak ulang.
CREATE TABLE IF NOT EXISTS pengajuan_honor (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bulan TEXT NOT NULL UNIQUE,
  tahun INTEGER NOT NULL,
  urut INTEGER NOT NULL,
  nomor TEXT NOT NULL,
  tanggal_surat TEXT NOT NULL,
  dibuat_oleh INTEGER REFERENCES pengguna(id) ON DELETE SET NULL
);

-- Kelas terdaftar di sesi mana (Pagi/Siang). Satu kelas boleh di beberapa sesi.
CREATE TABLE IF NOT EXISTS kelas_slot (
  kelas_id INTEGER NOT NULL REFERENCES kelas(id) ON DELETE CASCADE,
  slot_id INTEGER NOT NULL REFERENCES slot(id) ON DELETE CASCADE,
  PRIMARY KEY (kelas_id, slot_id)
);

